// @ts-check
import { Box3, Mesh, Vector3 } from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { MeshoptDecoder } from 'three/examples/jsm/libs/meshopt_decoder.module.js';
import { zoneForMaterial } from '../materials/zones.js';
import { loadTextureSet } from '../materials/textureSet.js';
import { createCuticleMaterial } from '../materials/cuticleMaterial.js';
import { createEyeMaterial, createOcellusMaterial } from '../materials/eyeMaterial.js';
import { applyMetalTransition, createMetalControls, createMetalUniforms, setAdvanceFrame } from '../materials/metalTransition.js';
import { advanceFrame } from '../materials/metalAdvance.js';

const MODEL_URL = `${import.meta.env.BASE_URL}models/mantis-head.glb`;

/**
 * Loads the head generated by tools/blender/build_head.py (web frame: +Y up, face toward +Z),
 * meshopt-compressed by `npm run model:build`, and replaces its clay materials by zone with the
 * viewer materials (baked cuticle maps for the tier, procedural eyes), all sharing the skin → metal
 * transition. Its controls are returned in `head.userData.metal`.
 * @param {import('three').WebGLRenderer} renderer
 * @param {import('../quality/tiers.js').TierName} tier texture size
 * @returns {Promise<import('three').Group>}
 */
export async function loadHead(renderer, tier) {
  const [gltf, maps] = await Promise.all([
    new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).loadAsync(MODEL_URL),
    loadTextureSet(renderer, tier).catch((error) => {
      console.error('Cuticle textures failed to load, using flat colors', error);
      return null;
    }),
  ]);
  const head = gltf.scene;
  head.name = 'mantis-head';

  /** One material per zone, shared by every mesh of that zone. */
  const materials = {
    skin: createCuticleMaterial('skin', maps),
    antenna: createCuticleMaterial('antenna', maps),
    palp: createCuticleMaterial('palp', maps),
    mandible: createCuticleMaterial('mandible', maps),
    eye: createEyeMaterial(),
    ocellus: createOcellusMaterial(),
  };
  const metalUniforms = createMetalUniforms();
  for (const material of Object.values(materials)) applyMetalTransition(material, metalUniforms);

  const mandibles = new Box3();
  const body = new Box3(); // without the long antennae, which would leave half the slider to their tips
  head.updateMatrixWorld(true); // bounds below are in world space, like the shader's positions
  head.traverse((object) => {
    if (!(object instanceof Mesh)) return;
    object.castShadow = true;
    object.receiveShadow = true;
    const zone = zoneForMaterial(object.material.name);
    if (zone) {
      object.material.dispose();
      object.material = materials[zone];
    }
    if (zone === 'mandible') mandibles.expandByObject(object);
    if (zone !== 'antenna') body.expandByObject(object);
  });

  // The metal grows from between the mandible tips toward the vertex; the antennae beyond the body's
  // reach saturate the field and turn last.
  const mouth = mandibles.isEmpty() ? new Vector3() : mandibles.getCenter(new Vector3()).setY(mandibles.min.y);
  setAdvanceFrame(metalUniforms, advanceFrame(body, mouth));
  head.userData.metal = createMetalControls(metalUniforms, { eye: materials.eye });
  return head;
}
